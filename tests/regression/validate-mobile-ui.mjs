assert.match(accountLedger, /title\.textContent = next === "spend" \? "Record spending"/);
assert.match(accountLedger, /target\?\.focus\(phone \? \{ preventScroll:true \} : undefined\)/);
assert.match(mobile, /@media \(max-width: 340px\)[\s\S]*data-paid-expense-row/);
